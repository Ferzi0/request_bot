def chars(count: int) -> str:
    """«1 символ», «2 символа», «5 символов» — число со словом в нужной форме."""
    if count % 10 == 1 and count % 100 != 11:
        word = "символ"
    elif 2 <= count % 10 <= 4 and not 12 <= count % 100 <= 14:
        word = "символа"
    else:
        word = "символов"
    return f"{count} {word}"
